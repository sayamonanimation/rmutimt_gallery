--  Helper: ให้โค้ดเดิมเรียก FIND_IN_SET(needle, csv) ได้เหมือน MySQL
--  คืนค่าตำแหน่ง (>=1) ถ้าเจอ, 0 ถ้าไม่เจอ  -> ใช้เป็นเงื่อนไข truthy ได้
-- ------------------------------------------------------------
-- ------------------------------------------------------------
--  Helper: shim ให้โค้ดที่เขียนแบบ MySQL ยังใช้ได้
--  DATABASE()  -> ชื่อ schema ปัจจุบัน (ปกติ 'public')
--  ใช้ในเควรี information_schema เช่น  WHERE table_schema = DATABASE()
-- ------------------------------------------------------------
DROP FUNCTION IF EXISTS database();
DROP FUNCTION IF EXISTS find_in_set(text, text);

CREATE OR REPLACE FUNCTION database()
RETURNS text
LANGUAGE sql
STABLE
AS $$
    SELECT current_schema()::text;
$$;

CREATE OR REPLACE FUNCTION find_in_set(needle text, haystack text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT needle = ANY(
        string_to_array(regexp_replace(COALESCE(haystack, ''), '\s', '', 'g'), ',')
    );
$$;

