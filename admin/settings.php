    function previewAdvisorAvatar(event) {
      const input = event.target;
      if (!input.files || !input.files[0]) return;
      const maxBytes = 2 * 1024 * 1024;
      if (input.files[0].size > maxBytes) {
        window.alert('ไฟล์ต้องไม่เกิน 2MB');
        input.value = '';
        return;
      }
      const reader = new FileReader();
      reader.onload = function (e) {
        const previewContainer = document.getElementById('advisor-preview-container');
        const cropperContainer = document.getElementById('advisor-cropper-container');
        const cropperImage = document.getElementById('advisor-cropper-image');

        if (previewContainer) previewContainer.classList.add('hidden');
        if (cropperContainer) cropperContainer.classList.remove('hidden');

        cropperImage.src = e.target.result;

        if (advisorCropper) {
            advisorCropper.destroy();
        }
        advisorCropper = new Cropper(cropperImage, {
            aspectRatio: 1,
            viewMode: 1,
            autoCropArea: 1,
        });
      };
      reader.readAsDataURL(input.files[0]);
    }

