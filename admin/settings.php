    header('Location: ../index.php');
    exit;
}

require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../config/csrf.php';
require_once __DIR__ . '/image_compress.php';

$flashError = '';
$flashSuccess = '';

if (isset($_SESSION['flash_error'])) {
    $flashError = (string) $_SESSION['flash_error'];
    unset($_SESSION['flash_error']);
}
if (isset($_SESSION['flash_success'])) {
    $flashSuccess = (string) $_SESSION['flash_success'];
    unset($_SESSION['flash_success']);
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && !csrf_verify($_POST['csrf_token'] ?? null)) {
    $_SESSION['flash_error'] = 'คำขอไม่ถูกต้องหรือโทเค็นหมดอายุ กรุณาลองใหม่อีกครั้ง';
    header('Location: settings.php');
    exit;
}

try {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS system_settings (
            key_name VARCHAR(100) PRIMARY KEY,
            value_text VARCHAR(255) NOT NULL
        )"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS advisors (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            prefix VARCHAR(30) NOT NULL,
            full_name VARCHAR(190) NOT NULL,
            avatar_filename VARCHAR(255),
            is_active SMALLINT NOT NULL DEFAULT 1,
            created_at TIMESTAMP NOT NULL DEFAULT now()
        )"
    );
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_advisors_active ON advisors (is_active)");
} catch (Throwable $e) {
    error_log('[ADMIN_SETTINGS] ensure tables failed: ' . $e->getMessage());
    $flashError = 'ไม่สามารถเตรียมโครงสร้างข้อมูลระบบตั้งค่าได้';
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = (string) ($_POST['action'] ?? '');

    if (isset($_POST['update_advisor_avatar']) && (string) $_POST['update_advisor_avatar'] === '1') {
        $advisorId = (int) ($_POST['advisor_id'] ?? 0);
        if ($advisorId <= 0) {
            $_SESSION['flash_error'] = 'คำขอเปลี่ยนรูปอาจารย์ไม่ถูกต้อง';
            header('Location: settings.php');
            exit;
        }

        try {
            $sel = $pdo->prepare('SELECT avatar_filename FROM advisors WHERE id = :id LIMIT 1');
            $sel->execute([':id' => $advisorId]);
            $advRow = $sel->fetch(PDO::FETCH_ASSOC);
            if (!$advRow) {
                $_SESSION['flash_error'] = 'ไม่พบข้อมูลอาจารย์ที่ปรึกษา';
                header('Location: settings.php');
                exit;
            }

            $oldFilename = trim((string) ($advRow['avatar_filename'] ?? ''));

            if (!isset($_FILES['advisor_avatar']) || !is_array($_FILES['advisor_avatar'])) {
                $_SESSION['flash_error'] = 'กรุณาเลือกไฟล์รูปภาพ';
                header('Location: settings.php');
                exit;
            }

            $fileErr = (int) ($_FILES['advisor_avatar']['error'] ?? UPLOAD_ERR_NO_FILE);
            if ($fileErr !== UPLOAD_ERR_OK) {
                $_SESSION['flash_error'] = 'อัปโหลดไฟล์ไม่สำเร็จ กรุณาลองใหม่';
                header('Location: settings.php');
                exit;
            }

            $uploadDir = __DIR__ . '/../uploads/advisors/';
            if (!is_dir($uploadDir)) {
                mkdir($uploadDir, 0755, true);
            }

            $newFilename = saveLocalUploadedImageAsWebp($_FILES['advisor_avatar'], $uploadDir, 'adv_', 500);
            if ($newFilename === null) {
                $_SESSION['flash_error'] = 'ไม่สามารถบันทึกไฟล์รูปภาพได้';
                header('Location: settings.php');
                exit;
            }

            $upd = $pdo->prepare('UPDATE advisors SET avatar_filename = :fn WHERE id = :id');
            $upd->execute([':fn' => $newFilename, ':id' => $advisorId]);

            if ($oldFilename !== '') {
                $oldPath = $uploadDir . basename($oldFilename);
                if (is_file($oldPath)) {
                    @unlink($oldPath);
                }
            }

            $_SESSION['flash_success'] = 'อัปเดตรูปอาจารย์ที่ปรึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] update advisor avatar failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถอัปเดตรูปอาจารย์ได้';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'toggle_registration') {
        $isOpen = isset($_POST['registration_open']) ? '1' : '0';
        try {
            $stmt = $pdo->prepare(
                "INSERT INTO system_settings (key_name, value_text)
                 VALUES ('student_registration_open', :value_text)
                 ON CONFLICT (key_name) DO UPDATE SET value_text = EXCLUDED.value_text"
            );
            $stmt->execute([':value_text' => $isOpen]);
            $_SESSION['flash_success'] = $isOpen === '1'
                ? 'เปิดรับสมัครนักศึกษาเรียบร้อยแล้ว'
                : 'ปิดรับสมัครนักศึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] toggle registration failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถอัปเดตสถานะการรับสมัครได้';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'add_year') {
        $year = trim((string) ($_POST['academic_year'] ?? ''));
        if ($year === '') {
            $_SESSION['flash_error'] = 'กรุณาระบุปีการศึกษา';
            header('Location: settings.php');
            exit;
        }

        try {
            $insert = $pdo->prepare('INSERT INTO academic_years (year) VALUES (:year)');
            $insert->execute([':year' => $year]);
            $_SESSION['flash_success'] = 'เพิ่มปีการศึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] add year failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถเพิ่มปีการศึกษาได้ (อาจมีข้อมูลซ้ำ)';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'delete_year') {
        $yearId = (int) ($_POST['year_id'] ?? 0);
        if ($yearId <= 0) {
            $_SESSION['flash_error'] = 'คำขอลบปีการศึกษาไม่ถูกต้อง';
            header('Location: settings.php');
            exit;
        }

        try {
            $delete = $pdo->prepare('DELETE FROM academic_years WHERE id = :id');
            $delete->execute([':id' => $yearId]);
            $_SESSION['flash_success'] = 'ลบปีการศึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] delete year failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถลบปีการศึกษาได้ เนื่องจากมีโครงงานอ้างอิงอยู่';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'add_category') {
        $categoryName = trim((string) ($_POST['category_name'] ?? ''));
        if ($categoryName === '') {
            $_SESSION['flash_error'] = 'กรุณาระบุชื่อหมวดหมู่';
            header('Location: settings.php');
            exit;
        }

        try {
            $insert = $pdo->prepare('INSERT INTO categories (name) VALUES (:name)');
            $insert->execute([':name' => $categoryName]);
            $_SESSION['flash_success'] = 'เพิ่มหมวดหมู่เรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] add category failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถเพิ่มหมวดหมู่ได้ (อาจมีข้อมูลซ้ำ)';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'delete_category') {
        $categoryId = (int) ($_POST['category_id'] ?? 0);
        if ($categoryId <= 0) {
            $_SESSION['flash_error'] = 'คำขอลบหมวดหมู่ไม่ถูกต้อง';
            header('Location: settings.php');
            exit;
        }

        try {
            $delete = $pdo->prepare('DELETE FROM categories WHERE id = :id');
            $delete->execute([':id' => $categoryId]);
            $_SESSION['flash_success'] = 'ลบหมวดหมู่เรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] delete category failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถลบหมวดหมู่ได้ เนื่องจากมีโครงงานอ้างอิงอยู่';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'add_advisor') {
        $prefix = trim((string) ($_POST['advisor_prefix'] ?? ''));
        $fullName = trim((string) ($_POST['advisor_full_name'] ?? ''));
        $avatarFilename = null;

        if ($prefix === '' || $fullName === '') {
            $_SESSION['flash_error'] = 'กรุณากรอกคำนำหน้าและชื่ออาจารย์ให้ครบถ้วน';
            header('Location: settings.php');
            exit;
        }

        // ระบบอัปโหลดรูปภาพ
        if (isset($_FILES['advisor_avatar']) && $_FILES['advisor_avatar']['error'] === UPLOAD_ERR_OK) {
            $uploadDir = __DIR__ . '/../uploads/advisors/';
            $avatarFilename = saveLocalUploadedImageAsWebp($_FILES['advisor_avatar'], $uploadDir, 'adv_', 500);
            if ($avatarFilename === null) {
                $_SESSION['flash_error'] = 'ไม่สามารถบันทึกไฟล์รูปภาพได้';
                header('Location: settings.php');
                exit;
            }
        }

        try {
            $insert = $pdo->prepare(
                'INSERT INTO advisors (prefix, full_name, avatar_filename, is_active)
                 VALUES (:prefix, :full_name, :avatar_filename, 1)'
            );
            $insert->execute([
                ':prefix' => $prefix,
                ':full_name' => $fullName,
                ':avatar_filename' => $avatarFilename,
            ]);
            $_SESSION['flash_success'] = 'เพิ่มอาจารย์ที่ปรึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] add advisor failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถเพิ่มอาจารย์ที่ปรึกษาได้';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'delete_advisor') {
        $advisorId = (int) ($_POST['advisor_id'] ?? 0);
        if ($advisorId <= 0) {
            $_SESSION['flash_error'] = 'คำขอลบอาจารย์ไม่ถูกต้อง';
            header('Location: settings.php');
            exit;
        }

        try {
            $delete = $pdo->prepare('DELETE FROM advisors WHERE id = :id');
            $delete->execute([':id' => $advisorId]);
            $_SESSION['flash_success'] = 'ลบอาจารย์ที่ปรึกษาเรียบร้อยแล้ว';
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] delete advisor failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถลบอาจารย์ที่ปรึกษาได้';
        }

        header('Location: settings.php');
        exit;
    }

    if ($action === 'toggle_advisor_status') {
        $advisorId = (int) ($_POST['advisor_id'] ?? 0);
        $nextStatus = (int) ($_POST['next_status'] ?? 0) === 1 ? 1 : 0;
        if ($advisorId <= 0) {
            $_SESSION['flash_error'] = 'คำขอปรับสถานะอาจารย์ไม่ถูกต้อง';
            header('Location: settings.php');
            exit;
        }

        try {
            $update = $pdo->prepare('UPDATE advisors SET is_active = :status WHERE id = :id');
            $update->execute([':status' => $nextStatus, ':id' => $advisorId]);
        } catch (Throwable $e) {
            error_log('[ADMIN_SETTINGS] toggle advisor status failed: ' . $e->getMessage());
            $_SESSION['flash_error'] = 'ไม่สามารถอัปเดตสถานะอาจารย์ได้';
        }

        header('Location: settings.php');
        exit;
    }
}

